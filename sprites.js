  const cache = {};
  function shade(hex, amt) {
    const n = parseInt(hex.slice(1), 16); let r = n >> 16, g = (n >> 8) & 255, b = n & 255;
    r = Math.max(0, Math.min(255, r + amt)); g = Math.max(0, Math.min(255, g + amt)); b = Math.max(0, Math.min(255, b + amt));
    return '#' + ((1 << 24) | (r << 16) | (g << 8) | b).toString(16).slice(1);
  }
  // draw a bitmap onto a canvas context at (x,y) with pixel size s
  function draw(ctx, key, x, y, s, color, outline = '#0b0618') {
    const rows = B[key]; if (!rows) return;
    const h = rows.length, w = rows[0].length;
    const on = (i, j) => j >= 0 && j < h && i >= 0 && i < w && rows[j][i] === '#';
    if (outline) {
      ctx.fillStyle = outline;
      for (let j = -1; j <= h; j++) for (let i = -1; i <= w; i++) {
        if (on(i, j)) continue;
        if (on(i - 1, j) || on(i + 1, j) || on(i, j - 1) || on(i, j + 1)) ctx.fillRect(x + i * s, y + j * s, s, s);
      }
    }
    const hi = shade(color, 70), lo = shade(color, -60);
    for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) if (on(i, j)) {
      ctx.fillStyle = !on(i, j - 1) ? hi : (!on(i, j + 1) || !on(i + 1, j)) ? lo : color;
      ctx.fillRect(x + i * s, y + j * s, s, s);
    }
  }
